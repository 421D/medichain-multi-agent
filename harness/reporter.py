"""Generate markdown and JSON evaluation reports.

Markdown = human-readable, for paper inclusion.
JSON = structured, for frontend Evaluation page consumption.
"""
from dataclasses import asdict
from datetime import datetime

from harness.metrics import EvaluationMetrics, ScoredResult


def generate_report(
    variant_metrics: dict[str, EvaluationMetrics],
    scored_by_variant: dict[str, list[ScoredResult]] | None = None,
) -> str:
    """Generate a markdown evaluation report comparing variants."""
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "# MediChain Evaluation Report",
        "",
        f"> Generated: {now}",
        "",
        "## Summary",
        "",
        "| Variant | Top-1 Acc | Top-3 Recall | Safety Recall | Missed Critical | Debate Avg | Cases |",
        "|---------|-----------|--------------|---------------|-----------------|------------|-------|",
    ]

    for name, m in variant_metrics.items():
        lines.append(
            f"| {name} | {m.top1_accuracy:.1%} | {m.top3_recall:.1%} | "
            f"{m.safety_flag_recall:.1%} | {m.missed_critical} | "
            f"{m.debate_rounds_avg:.1f} | {m.total_cases} |"
        )

    lines.extend(["", "## Debate Analysis", ""])

    for name, m in variant_metrics.items():
        if m.debate_rounds_avg > 0:
            lines.extend([
                f"### {name}",
                f"- Average debate rounds: {m.debate_rounds_avg:.1f}",
                f"- Challenge acceptance rate: {m.challenge_acceptance_rate:.1%}",
                f"- Diagnosis revision rate: {m.diagnosis_revision_rate:.1%}",
                "",
            ])

    # Per-case breakdown
    if scored_by_variant:
        lines.extend(["## Case-by-Case Breakdown", ""])
        for variant_name, scored_list in scored_by_variant.items():
            lines.append(f"### {variant_name}")
            lines.append("")
            lines.append("| Case | Top-1 | Top-3 | Safety | Debate Rounds | Time (s) |")
            lines.append("|------|-------|-------|--------|---------------|----------|")
            for r in scored_list:
                t1 = "✓" if r.top1_correct else "✗"
                t3 = "✓" if r.top3_recall else "✗"
                sf = "✓" if r.safety_flag_correct else "✗"
                err = f" ⚠ {r.error[:40]}" if r.error else ""
                lines.append(
                    f"| {r.case_id} {r.case_name}{err} | {t1} | {t3} | {sf} "
                    f"| {r.debate_rounds} | {r.total_time_seconds:.1f} |"
                )
            lines.append("")

    lines.extend(["---", "", "*Report generated by MediChain Evaluation Harness*"])

    return "\n".join(lines)


def generate_json_report(
    variant_metrics: dict[str, EvaluationMetrics],
    scored_by_variant: dict[str, list[ScoredResult]],
) -> dict:
    """Generate a structured JSON report for the frontend Evaluation page.

    Shape:
    {
      "generated_at": "2026-04-08 14:22",
      "variants": [
        {
          "name": "v2_debate",
          "metrics": { top1_accuracy, top3_recall, safety_flag_recall, ... },
          "cases": [
            {
              "case_id", "case_name",
              "top1_correct", "top3_recall", "safety_flag_correct",
              "debate_rounds", "challenges_accepted", "challenges_refuted",
              "total_time_seconds",
              "ai_primary_diagnosis", "ai_top3", "ai_safety_flag", "ai_final_assessment",
              "ground_truth_primary", "ground_truth_safety", "ground_truth_ddx", "ground_truth_tests",
              "debate_summary": [{round_number, challenges_count, responses_count, resolution}],
              "error"
            }
          ]
        }
      ]
    }
    """
    return {
        "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "variants": [
            {
                "name": name,
                "metrics": asdict(variant_metrics[name]),
                "cases": [asdict(r) for r in scored_by_variant.get(name, [])],
            }
            for name in variant_metrics
        ],
    }
